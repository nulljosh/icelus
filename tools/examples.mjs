// Writes docs/EXAMPLES.md from the worked examples in src/lib/agentkit.js. Run: node tools/examples.mjs
import { writeFileSync } from 'node:fs';
import { EXAMPLES, exampleProject, exampleText } from '../src/lib/agentkit.js';

const parts = EXAMPLES.map(({ slug, title, screens }) => `## ${title}

Read it as a project: \`resources/read\` with \`icelus://examples/${slug}\`.

${screens.map(([name, source]) => `**${name}**, typed:

\`\`\`
${source}
\`\`\``).join('\n\n')}

Drawn:

\`\`\`
${exampleText(exampleProject(slug))}
\`\`\`
`);

writeFileSync(new URL('../docs/EXAMPLES.md', import.meta.url), `# Worked examples

Each example is a small flow typed in Icelus's syntax, the same lines an agent writes for
\`sketch_to_wireframe\`. Every one passes \`critique_project\` with nothing to fix: each form shows what a
wrong entry looks like and each list has an empty state. This file is generated by \`node tools/examples.mjs\`.

${parts.join('\n')}`);
console.log(`docs/EXAMPLES.md: ${EXAMPLES.length} examples`);
