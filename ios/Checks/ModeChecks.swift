func runModeChecks() {
    func part(_ id: String, _ col: Int, _ row: Int) -> Element { createElement(presets.first { $0.id == id }!, col: col, row: row) }
    var box = part("card", 2, 2); box.style = "double"
    func text(_ els: [Element]) -> String { gridToText(renderElements(els, cols: 30, rows: 10)) }
    let before = text([box])
    let ascii = setMode([box], "ascii")
    check(canvasMode(ascii) == "ascii" && text(ascii).contains("+") && !text(ascii).contains("╔"), "modes: ascii draws the whole canvas in ascii")
    check(!text(ascii + [part("card", 15, 2)]).contains("┌"), "modes: the mode wins over a part added after it")
    check(text(setMode(ascii, "heavy")).contains("┏"), "modes: heavy")
    check(text(setMode(ascii, nil)) == before && setMode(ascii, nil).count == 1, "modes: clearing goes back")
    check(setMode([box], "invert") == [box], "modes: only line sets are modes")
    let screen = Element(id: "s", presetId: "screen", label: "Screen", template: screenFrame("Screen", width: 40, height: 30), width: 40, height: 30, col: 0, row: 0, text: "Screen")
    let withScreen = setMode([screen, box], "heavy")
    check(!partsInside(withScreen, screen).contains { $0.canvas }, "modes: the canvas part is never inside a screen")
    check(!critique(withScreen, cols: 60, rows: 30).contains { $0.id == withScreen.last!.id }, "modes: review skips the canvas part")
    let a = part("button", 1, 1), b = part("button", 1, 5)
    var els = setVar([screen, a, b], "space", 3)
    els = autoLayout(els, updateElement(els, id: "s", auto: AutoLayout(gap: 1, pad: 1, gapVar: "space")))
    func gapOf(_ list: [Element]) -> Int { list.first { $0.id == b.id }!.row - (list.first { $0.id == a.id }!.row + a.height) }
    check(gapOf(els) == 3, "modes: a screen bound to a variable uses its value")
    els = autoLayout(els, setVar(els, "space", 0))
    check(gapOf(els) == 0, "modes: changing the variable restacks the screen")
    els = setVar(els, "space", nil)
    check(els.first { $0.id == "s" }!.auto == AutoLayout(gap: 0, pad: 1) && !els.contains { $0.canvas }, "modes: removing a variable leaves its last value")
    check(cleanVars(["ok": 2, "Bad Name": 1, "big": 99, "neg": -1, "str": "2", "flag": true]) == ["ok": 2], "modes: vars are cleaned")
    let many = Dictionary(uniqueKeysWithValues: (0..<40).map { ("v\($0)", 1 as Any) })
    check(cleanVars(many).count == varMax && setVar([box], "Not OK", 1) == [box], "modes: vars are capped and names checked")
    var state = EditorState(cols: 30, rows: 10)
    state.elements = setVar(setMode([box], "rounded"), "gutter", 2)
    let back = parseProject(serializeProject(state))?.elements ?? []
    check(canvasMode(back) == "rounded" && canvasVars(back) == ["gutter": 2], "modes: mode and vars survive a save")
    state.elements = updateElement([screen], id: "s", auto: AutoLayout(gap: 1, pad: 2, gapVar: "gutter"))
    check(parseProject(serializeProject(state))?.elements[0].auto == AutoLayout(gap: 1, pad: 2, gapVar: "gutter"), "modes: a bound gap survives a save")
    let styled = setGridStyle([], "phone", ColumnGrid(cols: 4, gutter: 1, baseline: 2))
    check(canvasGrids(styled)["phone"]?.baseline == 2 && canvasGrids(setGridStyle(styled, "phone", nil)).isEmpty && setGridStyle([], "Bad Name", ColumnGrid()).isEmpty, "modes: named grid styles")
    var gs = EditorState(cols: 20, rows: 10)
    gs.elements = styled
    check(parseProject(serializeProject(gs))?.elements.first { $0.canvas }?.grids["phone"] == ColumnGrid(cols: 4, gutter: 1, baseline: 2), "modes: grid styles survive a save")

    // Color and width variables: bound parts follow, the mode flips them, removing lets go and keeps the value.
    let c1 = part("card", 2, 2), c2 = part("card", 20, 2)
    var cv = setColorVar([c1, c2], "brand", [4, 12])
    cv = bindVar(cv, id: c1.id, key: "ink", name: "brand")
    cv = bindVar(cv, id: c2.id, key: "paper", name: "brand")
    check(cv.first { $0.id == c1.id }!.ink == 4 && cv.first { $0.id == c2.id }!.paper == 4, "color vars: binding sets the color")
    cv = setColorVar(cv, "brand", [1, 9])
    check(cv.first { $0.id == c1.id }!.ink == 1, "color vars: changing the color repaints bound parts")
    cv = setColorMode(cv, "dark")
    check(colorMode(cv) == "dark" && cv.first { $0.id == c1.id }!.ink == 9 && cv.first { $0.id == c2.id }!.paper == 9, "color vars: dark mode flips bound parts")
    let byHand = updateElement(cv, id: c1.id, ink: 2, paper: nil)
    check(byHand.first { $0.id == c1.id }!.ink == 2 && byHand.first { $0.id == c1.id }!.inkVar == nil, "color vars: a hand-picked color lets go")
    let gone = setColorVar(setColorMode(cv, "light"), "brand", nil)
    check(gone.first { $0.id == c1.id }!.ink == 1 && gone.first { $0.id == c1.id }!.inkVar == nil && !gone.contains { $0.canvas }, "color vars: removing keeps the value and drops the empty canvas part")
    check(setColorVar([c1], "x", [1, 99]) == [c1] && bindVar([c1], id: c1.id, key: "ink", name: "nope") == [c1], "color vars: bad colors and unknown names are refused")
    var wv = bindVar(setWidthVar([c1], "col", 30), id: c1.id, key: "width", name: "col")
    check(wv.first { $0.id == c1.id }!.width == 30, "width vars: binding resizes")
    wv = setWidthVar(wv, "col", 18)
    check(wv.first { $0.id == c1.id }!.width == 18 && wv.first { $0.id == c1.id }!.template.allSatisfy { $0.count <= 18 }, "width vars: changing the width resizes bound parts")
    var vs = EditorState(cols: 60, rows: 20)
    vs.elements = setColorMode(bindVar(setMode(cv, "heavy"), id: c1.id, key: "ink", name: "brand"), "dark")
    vs.elements = bindVar(setWidthVar(vs.elements, "col", 24), id: c1.id, key: "width", name: "col")
    let vb = parseProject(serializeProject(vs))?.elements ?? []
    let p1 = vb.first { !$0.canvas && $0.inkVar != nil }
    check(canvasColors(vb) == ["brand": [1, 9]] && canvasWidths(vb) == ["col": 24] && colorMode(vb) == "dark" && canvasMode(vb) == "heavy", "variables: canvas fields survive a save")
    check(p1?.inkVar == "brand" && p1?.widthVar == "col" && p1?.ink == 9 && p1?.width == 24, "variables: bindings survive a save")
    check(cleanColorVars(["ok": [1, 2], "bad": [1, 99], "Bad Name": [1, 2], "flag": [true, 1]]) == ["ok": [1, 2]] && cleanWidthVars(["w": 10, "z": 0, "big": 900]) == ["w": 10], "variables: files are cleaned")
}
